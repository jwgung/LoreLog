//! life-diary: the day's diary from the command line (what the HTTP API does, for scripts and checks).
use std::io::Read;
use std::process::ExitCode;

use life_server::assistant::{chat, context, diary, senders};
use life_server::config::Paths;
use serde_json::{Value, json};

const HELP: &str = "\
usage: life-diary [date] [--context] [--json] [--save] [--senders] [--set-allow] [--chatlog]

The day's diary from the command line. date: YYYY-MM-DD (default: today)

  --context     print the context sent to the LLM for the day's summary and exit
  --json        print the stored draft, corrections and reflection of the day as JSON
  --save        read {corrections:[{wrong,right}], reflection} from stdin and store it
  --senders     print notification senders of the last 14 days with their allowed flag (JSON)
  --set-allow   read {allow:['label: title' | 'label: *']} from stdin and store it
  --chatlog     print the day's chat exchange as JSON";

fn stdin_json() -> Result<Value, String> {
    let mut s = String::new();
    std::io::stdin()
        .read_to_string(&mut s)
        .map_err(|e| e.to_string())?;
    serde_json::from_str(&s).map_err(|e| format!("stdin is not JSON: {e}"))
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.iter().any(|a| a == "-h" || a == "--help") {
        println!("{HELP}");
        return ExitCode::SUCCESS;
    }
    let flag = |f: &str| args.iter().any(|a| a == f);
    let day = args
        .iter()
        .find(|a| !a.starts_with('-'))
        .cloned()
        .unwrap_or_else(|| chrono::Local::now().format("%Y-%m-%d").to_string());
    if chrono::NaiveDate::parse_from_str(&day, "%Y-%m-%d").is_err() {
        eprintln!("date must be YYYY-MM-DD: {day}");
        return ExitCode::from(2);
    }
    let paths = Paths::from_env();
    let result: Result<(), String> = if flag("--chatlog") {
        println!("{}", json!({"messages": chat::chat_history(&paths, &day)}));
        Ok(())
    } else if flag("--senders") {
        println!("{}", Value::Array(senders::list_senders(&paths, 14)));
        Ok(())
    } else if flag("--set-allow") {
        stdin_json().and_then(|v| {
            let items = v
                .get("allow")
                .and_then(Value::as_array)
                .cloned()
                .unwrap_or_default();
            senders::save_allow(&paths, &items).map_err(|e| e.to_string())
        })
    } else if flag("--json") {
        println!("{}", diary::read_day(&paths, &day));
        Ok(())
    } else if flag("--save") {
        stdin_json().and_then(|v| diary::save_user(&paths, &day, &v).map_err(|e| e.to_string()))
    } else if flag("--context") {
        println!("{}", context::build_context(&paths, &day, true));
        Ok(())
    } else {
        Err("the summary is not generated by this build yet; use --context, --json, --senders or --chatlog".into())
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("{e}");
            ExitCode::FAILURE
        }
    }
}
